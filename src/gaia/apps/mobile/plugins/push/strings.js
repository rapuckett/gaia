/* global __dirname */

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const { OPEN_ONLY_RESOURCE, PUSH_LOC_KEY, STRING_KEYS, androidResourceName } = require('./constants');

const LOCALES_DIR = path.resolve(__dirname, '../../../webui/src/i18n/locales');

/** Every message of one webui catalog, read from its TypeScript source (it imports types only). */
function loadCatalog(lang) {
    const file = path.join(LOCALES_DIR, `${lang}.ts`);
    if (!fs.existsSync(file)) {
        throw new Error(`withPush: there is no webui catalog for "${lang}" at ${file}; the notification strings are generated from it.`);
    }
    const ts = require('typescript');
    const js = ts.transpileModule(fs.readFileSync(file, 'utf8'), {
        compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
    }).outputText;
    const module = { exports: {} };
    const refuse = (id) => {
        throw new Error(`withPush: ${file} now imports "${id}" at runtime, which the strings generator can't load. Keep the catalog's imports type-only.`);
    };
    vm.runInNewContext(js, { module, exports: module.exports, require: refuse });
    const locale = module.exports[lang];
    if (!locale || typeof locale.messages !== 'object') throw new Error(`withPush: ${file} no longer exports \`${lang}\` with its messages.`);
    return locale.messages;
}

/** The notification strings in `lang`, by catalog key; a key missing from the catalog fails the build. */
function pushStrings(lang) {
    const messages = loadCatalog(lang);
    const out = {};
    for (const key of STRING_KEYS) {
        const value = messages[key];
        if (typeof value !== 'string' || value === '') throw new Error(`withPush: the ${lang} catalog has no "${key}", which the notification code needs.`);
        out[key] = value;
    }
    return out;
}

function escapeStrings(value) {
    return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');
}

/** A Localizable.strings file: every catalog key as itself, plus the relay's loc-key as the generic body. */
function iosStringsFile(strings) {
    const entries = { ...strings, [PUSH_LOC_KEY]: strings['mobileApp.push.generic.body'] };
    return `${Object.entries(entries)
        .map(([key, value]) => `"${escapeStrings(key)}" = "${escapeStrings(value)}";`)
        .join('\n')}\n`;
}

function escapeAndroid(value) {
    const xml = value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
    return xml.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/^([@?])/, '\\$1');
}

/** A res/values*\/ strings file holding the notification strings under androidResourceName(key). */
function androidStringsXml(strings) {
    const lines = Object.entries(strings).map(
        ([key, value]) => `    <string name="${androidResourceName(key)}">${escapeAndroid(value)}</string>`,
    );
    return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by plugins/withPush.js from the webui catalogs. -->\n<resources>\n${lines.join('\n')}\n</resources>\n`;
}

/** The tools whose approval notifications offer only Open (modules/gaia-push/openOnlyTools.json); anything but a list of tool ids fails the build. */
function openOnlyTools() {
    const file = path.resolve(__dirname, '../../modules/gaia-push/openOnlyTools.json');
    const tools = JSON.parse(fs.readFileSync(file, 'utf8')).tools;
    if (!Array.isArray(tools) || !tools.every((t) => typeof t === 'string' && /^[a-z0-9_]{1,64}$/.test(t))) {
        throw new Error(`withPush: "tools" in ${file} must be a list of tool ids ([a-z0-9_]).`);
    }
    return tools;
}

/** A res/values/ file holding the open-only tools as the string-array GaiaMessagingService reads. */
function androidOpenOnlyXml(tools) {
    const items = tools.map((t) => `        <item>${escapeAndroid(t)}</item>`);
    return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by plugins/withPush.js from modules/gaia-push/openOnlyTools.json. -->\n<resources>\n    <string-array name="${OPEN_ONLY_RESOURCE}">\n${items.join('\n')}${items.length ? '\n' : ''}    </string-array>\n</resources>\n`;
}

module.exports = { pushStrings, iosStringsFile, androidStringsXml, openOnlyTools, androidOpenOnlyXml };
