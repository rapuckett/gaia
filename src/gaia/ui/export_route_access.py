"""Export who may call each Agent UI API route, for the mobile app.

A paired phone reaches the device listener, which refuses some routes. The app
reads the committed ``routeAccess.gen.ts`` to show "change this on your PC"
instead of a control that can only fail. Classes come from each route's guard
dependencies (``gaia.ui.security``); a check made inside a handler is not seen
and stays ``remote``.

Usage::

    # Regenerate:
    python -m gaia.ui.export_route_access

    # Drift check — non-zero exit if the committed file or doc table is stale:
    python -m gaia.ui.export_route_access --check

The same run rewrites the route-class table in ``docs/sdk/sdks/agent-ui.mdx``
between its ``route-classes`` markers.

Run it from the repo root of the checkout ``gaia`` is imported from; it refuses
(exit 2) elsewhere. From another worktree, prefix ``PYTHONPATH=$PWD/src``.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Dict

from fastapi.routing import APIRoute

from gaia.ui._export_checkout import require_matching_checkout

ARTIFACT_PATH = (
    Path(__file__).resolve().parents[1]
    / "apps"
    / "mobile"
    / "src"
    / "api"
    / "routeAccess.gen.ts"
)

DOC_PATH = (
    Path(__file__).resolve().parents[3] / "docs" / "sdk" / "sdks" / "agent-ui.mdx"
)

DOC_BEGIN = (
    "{/* route-classes:begin (generated by python -m gaia.ui.export_route_access; "
    "do not edit) */}"
)
DOC_END = "{/* route-classes:end */}"

# (class key, label, who, routes text; None lists the routes)
DOC_CLASSES = (
    ("pc", "PC-only", "`pc`", None),
    ("pc_or_device", "Setup", "`pc`, or an allowed device", None),
    ("not_on_listener", "Not from a device", "`pc`, `tunnel`", None),
    ("pair", "Pairing", "a device on the listener, with no token", None),
    ("device", "Its own routes", "an allowed device", None),
    ("device_self", "Unpairing itself", "a device, pending or allowed", None),
    (
        "remote",
        "Everything else",
        "`pc`, `tunnel`, an allowed device",
        "Chats, documents, memory, reading goals and schedules, and the rest",
    ),
)

REGENERATE_HINT = "python -m gaia.ui.export_route_access"


def _guard_classes():
    from gaia.ui import security

    # In precedence order: a route with two guards takes the first one's class.
    return (
        (security.require_local_pc, "pc"),
        (security.require_pc_or_device, "pc_or_device"),
        (security.require_pc_or_allowed_device, "pc_or_device"),
        (security.refuse_on_device_listener, "not_on_listener"),
        (security.require_device_listener, "pair"),
        (security.require_allowed_device, "device"),
        (security.require_device, "device_self"),
    )


def _api_routes(routes):
    """Every ``APIRoute``, through the app's lazily included routers."""
    for route in routes:
        lazy = False
        for name in ("effective_candidates", "effective_low_priority_routes"):
            method = getattr(route, name, None)
            if callable(method):
                yield from _api_routes(method())
                lazy = True
        if lazy:
            continue
        original = getattr(route, "original_route", route)
        if isinstance(original, APIRoute):
            yield original
        elif hasattr(route, "routes"):
            yield from _api_routes(route.routes)


def build_access() -> Dict[str, str]:
    """``{"METHOD /path": class}`` for every ``/api/`` and ``/v1/`` route."""
    from gaia.ui.server import create_app

    app = create_app(db_path=":memory:")
    guards = _guard_classes()
    access: Dict[str, str] = {}
    for route in _api_routes(app.routes):
        if not route.path.startswith(("/api/", "/v1/")):
            continue
        calls = {d.call for d in route.dependant.dependencies}
        cls = next((name for guard, name in guards if guard in calls), "remote")
        for method in route.methods:
            access[f"{method} {route.path}"] = cls
    return dict(sorted(access.items()))


def render(access: Dict[str, str]) -> str:
    lines = [
        "// Copyright(C) 2026 Advanced Micro Devices, Inc. All rights reserved.",
        "// SPDX-License-Identifier: MIT",
        "",
        "// Generated from the backend's route guards; do not edit.",
        f"// Regenerate from the repo root: {REGENERATE_HINT}",
        "",
        "export type RouteAccessClass = "
        + " | ".join(
            f"'{c}'" for c in sorted({n for _, n in _guard_classes()} | {"remote"})
        )
        + ";",
        "",
        "export const ROUTE_ACCESS: Readonly<Record<string, RouteAccessClass>> = {",
    ]
    for key, cls in access.items():
        lines.append(f"    '{key}': '{cls}',")
    lines += ["};", ""]
    return "\n".join(lines)


def render_doc_section(access: Dict[str, str]) -> str:
    """The marked route-class table, markers included."""
    unknown = set(access.values()) - {key for key, *_ in DOC_CLASSES}
    if unknown:
        raise ValueError(
            f"route class(es) {sorted(unknown)} have no row in DOC_CLASSES in "
            f"{__file__}; add one so the doc table lists them."
        )
    lines = [DOC_BEGIN, "", "| Class | Who | Routes |", "|---|---|---|"]
    for key, label, who, text in DOC_CLASSES:
        routes = sorted(k for k, cls in access.items() if cls == key)
        if not routes:
            continue
        cell = text or ", ".join(f"`{r}`" for r in routes)
        lines.append(f"| {label} | {who} | {cell} |")
    lines += ["", DOC_END]
    return "\n".join(lines)


def update_doc(text: str, access: Dict[str, str]) -> str:
    """Replace the first begin marker through the last end marker."""
    start = text.find(DOC_BEGIN.split(" (generated")[0])
    end = text.rfind(DOC_END)
    if start < 0 or end < start:
        raise ValueError(
            f"{DOC_PATH} has no route-classes begin/end markers; "
            "add them around the route-class table."
        )
    return text[:start] + render_doc_section(access) + text[end + len(DOC_END) :]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the committed route access file is stale",
    )
    args = parser.parse_args(argv)

    refused = require_matching_checkout("gaia.ui.export_route_access")
    if refused is not None:
        return refused

    access = build_access()
    rendered = render(access)
    doc_current = DOC_PATH.read_text(encoding="utf-8")
    doc_rendered = update_doc(doc_current, access)
    if args.check:
        committed = (
            ARTIFACT_PATH.read_text(encoding="utf-8") if ARTIFACT_PATH.exists() else ""
        )
        stale = [
            path
            for path, old, new in (
                (ARTIFACT_PATH, committed, rendered),
                (DOC_PATH, doc_current, doc_rendered),
            )
            if old != new
        ]
        if stale:
            names = "\n".join(f"{path} is out of date" for path in stale)
            print(
                f"{names} with the Agent UI route guards.\n"
                f"Regenerate from the repo root: {REGENERATE_HINT}",
                file=sys.stderr,
            )
            return 1
        return 0

    ARTIFACT_PATH.write_text(rendered, encoding="utf-8", newline="\n")
    DOC_PATH.write_text(doc_rendered, encoding="utf-8", newline="\n")
    print(f"Wrote {ARTIFACT_PATH}\nWrote {DOC_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
